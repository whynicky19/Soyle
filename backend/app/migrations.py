"""Explicit, reproducible database migrations for Soyle.

Run from backend/: python -m app.migrations upgrade
The application startup intentionally does not apply these migrations.
"""

import json
import sys

from .database import connect, init_db, now_iso
from .exercise_engine import legacy_engine_payload, validate_version


def _columns(db, table: str) -> set[str]:
    if db.backend == "postgresql":
        return {
            row["column_name"]
            for row in db.execute(
                "SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=?",
                (table,),
            ).fetchall()
        }
    return {row["name"] for row in db.execute(f"PRAGMA table_info({table})").fetchall()}


def _migration_9_exercise_engine(db) -> None:
    id_column = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db.backend == "postgresql" else "INTEGER PRIMARY KEY AUTOINCREMENT"
    db.executescript(f"""
    CREATE TABLE IF NOT EXISTS exercise_versions (
        id {id_column},
        exercise_id BIGINT NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
        version INTEGER NOT NULL,
        title TEXT NOT NULL,
        mechanic TEXT NOT NULL,
        language TEXT NOT NULL DEFAULT 'ru',
        objective TEXT NOT NULL,
        instruction TEXT NOT NULL,
        response_mode TEXT NOT NULL,
        prompt_policy_json TEXT NOT NULL DEFAULT '{{}}',
        completion_rule_json TEXT NOT NULL DEFAULT '{{}}',
        content_json TEXT NOT NULL DEFAULT '{{}}',
        review_status TEXT NOT NULL DEFAULT 'pending',
        publication_status TEXT NOT NULL DEFAULT 'draft',
        created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at TEXT NOT NULL,
        published_at TEXT,
        UNIQUE(exercise_id,version)
    );
    CREATE TABLE IF NOT EXISTS exercise_stimuli (
        id {id_column},
        version_id BIGINT NOT NULL REFERENCES exercise_versions(id) ON DELETE CASCADE,
        stimulus_key TEXT NOT NULL,
        kind TEXT NOT NULL,
        label TEXT NOT NULL,
        speech TEXT NOT NULL,
        media_ref TEXT,
        position INTEGER NOT NULL DEFAULT 0,
        metadata_json TEXT NOT NULL DEFAULT '{{}}',
        UNIQUE(version_id,stimulus_key)
    );
    CREATE INDEX IF NOT EXISTS idx_exercise_versions_publication
        ON exercise_versions(publication_status,review_status,exercise_id,version);
    """)
    if "exercise_version_id" not in _columns(db, "sessions"):
        db.execute("ALTER TABLE sessions ADD COLUMN exercise_version_id BIGINT REFERENCES exercise_versions(id) ON DELETE SET NULL")

    rows = db.execute("SELECT * FROM exercises ORDER BY id").fetchall()
    for raw in rows:
        exercise = dict(raw)
        if db.execute("SELECT 1 FROM exercise_versions WHERE exercise_id=? LIMIT 1", (exercise["id"],)).fetchone():
            continue
        engine = legacy_engine_payload(exercise)
        candidate = {
            **exercise,
            **engine,
            "language": "ru",
            "title": exercise["title"],
            "instruction": exercise["instruction"],
        }
        errors = validate_version(candidate)
        public = bool(exercise["is_active"]) and exercise["module"] != "motor" and not errors
        review_status = "approved" if public else "unreviewed"
        publication_status = "published" if public else "internal_review" if exercise["module"] == "motor" else "archived"
        cursor = db.execute(
            """INSERT INTO exercise_versions(
                   exercise_id,version,title,mechanic,language,objective,instruction,response_mode,
                   prompt_policy_json,completion_rule_json,content_json,review_status,publication_status,created_at,published_at)
               VALUES(?,1,?,?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id""",
            (
                exercise["id"], exercise["title"], engine["mechanic"], "ru", engine["objective"], exercise["instruction"],
                engine["response_mode"], json.dumps(engine["prompt_policy"], ensure_ascii=False),
                json.dumps(engine["completion_rule"], ensure_ascii=False), json.dumps(engine["content"], ensure_ascii=False),
                review_status, publication_status, now_iso(), now_iso() if public else None,
            ),
        )
        version_id = cursor.fetchone()["id"]
        for position, stimulus in enumerate(engine["content"].get("stimuli", [])):
            db.execute(
                """INSERT INTO exercise_stimuli(version_id,stimulus_key,kind,label,speech,media_ref,position,metadata_json)
                   VALUES(?,?,?,?,?,?,?,?)""",
                (
                    version_id, stimulus["key"], "image", stimulus["label"], stimulus["speech"],
                    stimulus.get("media_ref"), position,
                    json.dumps({"hint": stimulus.get("hint", ""), "visual_token": stimulus.get("visual_token")}, ensure_ascii=False),
                ),
            )
    db.execute("UPDATE exercises SET is_active=0 WHERE module='motor'")


CONTENT_CONTRACT_CORRECTIONS = {
    "request": "Выбери предмет или собери короткую просьбу. Одной понятной карточки достаточно",
    "observation": "Выбери, кого или что видишь, и при желании добавь действие",
    "routine": "Выбери одно знакомое действие дня и сообщи о нём",
    "question": "Выбери готовый короткий вопрос: «Что это?» или «Где?»",
}


def _migration_10_content_contracts(db) -> None:
    """Create corrected immutable versions where legacy copy overpromised the runner."""
    for target, instruction in CONTENT_CONTRACT_CORRECTIONS.items():
        exercise = db.execute("SELECT id FROM exercises WHERE target=?", (target,)).fetchone()
        if not exercise:
            continue
        source = db.execute(
            """SELECT * FROM exercise_versions
               WHERE exercise_id=? AND publication_status='published'
               ORDER BY version DESC LIMIT 1""",
            (exercise["id"],),
        ).fetchone()
        if not source:
            continue
        source = dict(source)
        next_version = db.execute(
            "SELECT COALESCE(MAX(version),0)+1 next_version FROM exercise_versions WHERE exercise_id=?",
            (exercise["id"],),
        ).fetchone()["next_version"]
        db.execute(
            "UPDATE exercise_versions SET publication_status='archived' WHERE exercise_id=? AND publication_status='published'",
            (exercise["id"],),
        )
        cursor = db.execute(
            """INSERT INTO exercise_versions(
                   exercise_id,version,title,mechanic,language,objective,instruction,response_mode,
                   prompt_policy_json,completion_rule_json,content_json,review_status,publication_status,
                   created_by,created_at,published_at)
               VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id""",
            (
                exercise["id"], next_version, source["title"], source["mechanic"], source["language"],
                source["objective"], instruction, source["response_mode"], source["prompt_policy_json"],
                source["completion_rule_json"], source["content_json"], source["review_status"], "published",
                source["created_by"], now_iso(), now_iso(),
            ),
        )
        new_version_id = cursor.fetchone()["id"]
        stimuli = db.execute(
            "SELECT * FROM exercise_stimuli WHERE version_id=? ORDER BY position,id",
            (source["id"],),
        ).fetchall()
        for stimulus in stimuli:
            db.execute(
                """INSERT INTO exercise_stimuli(
                       version_id,stimulus_key,kind,label,speech,media_ref,position,metadata_json)
                   VALUES(?,?,?,?,?,?,?,?)""",
                (
                    new_version_id, stimulus["stimulus_key"], stimulus["kind"], stimulus["label"],
                    stimulus["speech"], stimulus["media_ref"], stimulus["position"], stimulus["metadata_json"],
                ),
            )
        db.execute("UPDATE exercises SET instruction=? WHERE id=?", (instruction, exercise["id"]))


MIGRATIONS = ((9, _migration_9_exercise_engine), (10, _migration_10_content_contracts))


def apply_migrations() -> list[int]:
    applied: list[int] = []
    with connect() as db:
        known = {row["version"] for row in db.execute("SELECT version FROM schema_migrations").fetchall()}
        for version, migration in MIGRATIONS:
            if version in known:
                continue
            migration(db)
            db.execute("INSERT INTO schema_migrations(version,applied_at) VALUES(?,?)", (version, now_iso()))
            applied.append(version)
    return applied


def main() -> int:
    if len(sys.argv) != 2 or sys.argv[1] != "upgrade":
        print("Usage: python -m app.migrations upgrade")
        return 2
    init_db()
    applied = apply_migrations()
    print("Applied migrations:", ", ".join(map(str, applied)) if applied else "none")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
