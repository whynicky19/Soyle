def _insert_p15_draft(db, fixture: dict) -> None:
    """Insert one immutable, unpublished P1.5 version and its review metadata."""
    candidate = {**fixture, "language": "ru"}
    errors = validate_version(candidate)
    if errors:
        raise RuntimeError(f"Invalid P1.5 fixture {fixture['target']}: {'; '.join(errors)}")
    exercise = db.execute("SELECT id FROM exercises WHERE target=? ORDER BY id LIMIT 1", (fixture["target"],)).fetchone()
    if exercise:
        exercise_id = exercise["id"]
    else:
        cursor = db.execute(
            """INSERT INTO exercises(module,title,instruction,difficulty,target,icon,skill,is_active)
               VALUES(?,?,?,?,?,?,?,0) RETURNING id""",
            (
                fixture["module"], fixture["title"], fixture["instruction"], fixture["difficulty"],
                fixture["target"], fixture["icon"], fixture["skill"],
            ),
        )
        exercise_id = cursor.fetchone()["id"]
    existing = db.execute(
        "SELECT id,content_json FROM exercise_versions WHERE exercise_id=? AND title=? AND publication_status='draft' ORDER BY version DESC LIMIT 1",
        (exercise_id, fixture["title"]),
    ).fetchone()
    if existing:
        revision = fixture.get("content", {}).get("revision")
        if not revision or json.loads(existing["content_json"]).get("revision") == revision:
            return
    next_version = db.execute(
        "SELECT COALESCE(MAX(version),0)+1 next_version FROM exercise_versions WHERE exercise_id=?",
        (exercise_id,),
    ).fetchone()["next_version"]
    cursor = db.execute(
        """INSERT INTO exercise_versions(
               exercise_id,version,title,mechanic,language,objective,instruction,response_mode,
               prompt_policy_json,completion_rule_json,content_json,review_status,publication_status,
               technical_status,methodology_status,release_status,method_card_json,created_at)
           VALUES(?,?,?,?,?,?,?,?,?,?,?,'pending','draft','automated_passed','pending','pending',?,?) RETURNING id""",
        (
            exercise_id, next_version, fixture["title"], fixture["mechanic"], "ru", fixture["objective"],
            fixture["instruction"], fixture["response_mode"],
            json.dumps(fixture["prompt_policy"], ensure_ascii=False),
            json.dumps(fixture["completion_rule"], ensure_ascii=False),
            json.dumps(fixture["content"], ensure_ascii=False),
            json.dumps(fixture["method_card"], ensure_ascii=False), now_iso(),
        ),
    )
    version_id = cursor.fetchone()["id"]
    asset_by_ref = {item["media_ref"]: item for item in fixture["content"].get("asset_registry", [])}
    for position, stimulus in enumerate(fixture["content"].get("stimuli", [])):
        asset = asset_by_ref.get(stimulus.get("media_ref"), {})
        db.execute(
            """INSERT INTO exercise_stimuli(version_id,stimulus_key,kind,label,speech,media_ref,position,metadata_json)
               VALUES(?,?,?,?,?,?,?,?)""",
            (
                version_id, stimulus["key"], "action_scene" if fixture["mechanic"] == "action_choice" else "image",
                stimulus["label"], stimulus["speech"], stimulus.get("media_ref"), position,
                json.dumps(
                    {
                        "hint": stimulus.get("hint", ""),
                        "alt": stimulus.get("alt", ""),
                        "origin": asset.get("origin", ""),
                        "license": asset.get("license", ""),
                    },
                    ensure_ascii=False,
                ),
            ),
        )
    db.execute(
        """INSERT INTO content_reviews(version_id,stage,decision,comment,reviewer_id,created_at)
           VALUES(?,'technical','automated_passed','Автоматическая проверка структуры пройдена; ручная техническая проверка ожидается',NULL,?)""",
        (version_id, now_iso()),
    )


