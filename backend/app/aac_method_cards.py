"""Describe the existing AAC interaction without inventing scores or expertise."""
from .p15_content import _method_card


def aac_method_card(version: dict) -> dict:
    content = version['content']
    labels = content.get('labels', [])
    card = _method_card(
        target_skill=version['objective'], skill_group=['Функциональная AAC-коммуникация'],
        child_instruction=content.get('instruction') or version['instruction'],
        stimuli_and_responses='Доступные карточки: ' + ', '.join(labels) + '. ' + content.get('criterion', 'Выбрать и озвучить доступное сообщение.'),
        prerequisites=['Ребёнку доступно нажатие или выбор карточки с подтверждением взрослого', 'Карточки обозначают знакомые человеку предметы, действия или состояния'],
        adult_guidance=['Предложите понятную ситуацию и дождитесь выбора ребёнка', 'Примите одну понятную карточку; не требуйте обязательной длинной фразы', 'Отреагируйте на смысл сообщения, включая отказ и просьбу остановиться', 'При показе образца отдельно отметьте помощь взрослого'],
        accepted_responses=['Выбор допустимой карточки или последовательности этого задания', 'Указание или взгляд с подтверждением взрослого как выполнение с поддержкой', 'Просьба о перерыве и отказ — отдельные допустимые исходы'],
        ambiguities=['Нажатие на карточку само по себе не доказывает спонтанную инициативу или понимание в другой ситуации', 'Предпочтение, чувство и отказ ребёнка нельзя оценивать как правильные или неправильные'],
        transfer=['Предложите те же карточки в знакомой реальной ситуации', 'Отдельно запишите, кому адресовано сообщение и какая помощь понадобилась'],
        result_rules=['Сохраняется участие и выбранное сообщение, без балла правильности', 'Помощь взрослого, отказ и перерыв учитываются отдельно', 'Предпросмотр взрослого не сохраняется как результат ребёнка'],
    )
    card.update(
        intended_for=['Люди, которым нужна поддержка доступного сообщения в знакомой ситуации'],
        difficulty_levels=['Фиксированный набор карточек и допустимых сочетаний; автоматического повышения сложности нет'],
        prompts=['Взрослый может повторить предложение или показать пример, затем дать время для собственного выбора'],
        stop_conditions=['Ребёнок сообщает отказ или выбирает перерыв', 'Ребёнок устал или испытывает дискомфорт', 'Не загружаются карточки или озвучка'],
        evidence_note='Описание действующей механики продукта. Клиническая эффективность и независимая экспертная проверка этого задания не заявлены.',
    )
    return card
