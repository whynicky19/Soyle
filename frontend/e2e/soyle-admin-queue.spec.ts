import AxeBuilder from "@axe-core/playwright";
import {expect, test} from "@playwright/test";

test("admin sees review queue, can find a draft, inspect blockers and distinguish demo library", async ({page}, info) => {
  test.setTimeout(60_000);
  await page.route("http://localhost:8010/**", route => route.continue({url: route.request().url().replace(":8010", ":8011")}));
  await page.goto("/app");
  await page.getByLabel("Логин", {exact: true}).fill("admin");
  await page.getByLabel("Пароль", {exact: true}).fill("Admin123!");
  await page.getByRole("button", {name: "Войти", exact: true}).click();
  await expect(page.getByRole("heading", {name: "Задания и проверка"})).toBeVisible();
  await expect(page.locator(".admin-review-item").first()).toBeVisible();
  const audit = await new AxeBuilder({page}).analyze();
  expect(audit.violations.filter(item => ["serious","critical"].includes(item.impact || ""))).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({path: info.outputPath("admin-review-queue.png"), fullPage: true});
  await page.getByLabel("Поиск по названию").fill("Понимание слов: игрушки");
  const draft = page.locator(".admin-review-item").filter({hasText: "Понимание слов: игрушки"});
  await expect(draft).toHaveCount(1);
  await draft.getByRole("button", {name: "Открыть проверку", exact: true}).click();
  await expect(page.getByText("Материал недоступен детям")).toBeVisible();
  await expect(page.getByRole("option", {name: "Методическая экспертиза"})).toHaveAttribute("disabled", "");
  await page.getByRole("button", {name: "Закрыть", exact: true}).click();
  await page.getByLabel("Поиск по названию").fill("");
  await page.getByRole("button", {name: "Готовы к публикации", exact: true}).click();
  await expect(page.getByText("По этим условиям ничего не найдено")).toBeVisible();
  await page.getByRole("button", {name: "Все", exact: true}).click();
  await page.getByLabel("Тип материала").selectOption("home");
  await expect(page.locator(".admin-home-review-item")).toHaveCount(12);
  await page.getByRole("button", {name: "Открыть инструкцию", exact: true}).first().click();
  await expect(page.getByText("Родитель пока не видит эти инструкции")).toBeVisible();
  await page.getByRole("button", {name: "Закрыть", exact: true}).click();
  await page.getByRole("button", {name: /Доступная библиотека/}).click();
  await expect(page.getByText("Демо · не утверждено").first()).toBeVisible();
  await page.getByRole("tab", {name: "Пользователи", exact: true}).click();
  await expect(page.getByRole("table", {name: "Взрослые аккаунты и их права доступа"})).toBeVisible();
  const usersAudit = await new AxeBuilder({page}).analyze();
  expect(usersAudit.violations.filter(item => ["serious","critical"].includes(item.impact || ""))).toEqual([]);
});
